#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_plugin_template_names_every_event_and_the_transport() {
        let source = plugin_source(Path::new("/opt/base/bin/base"));
        for needle in [
            MARKER,
            "Plugin.define",
            "execFile",
            "BASE_HEADLESS",
            "--harness opencode",
            "session-start",
            "user-prompt-submit",
            "pre-tool-use",
            "post-tool-use",
            "stop",
            "session-end",
        ] {
            assert!(source.contains(needle), "the plugin lost {needle}");
        }
        assert!(!source.contains("$("), "the plugin must not use shell interpolation");
        assert!(!source.contains("eval("), "the plugin must not eval");
    }

    #[test]
    fn a_relative_exe_falls_back_to_path() {
        assert_eq!(binary_literal(Path::new("target/debug/base")), "\"base\"");
        assert_eq!(binary_literal(Path::new("/opt/base/bin/base")), "\"/opt/base/bin/base\"");
    }

    #[test]
    fn an_empty_emission_prints_nothing() {
        assert_eq!(outbound("session-start", "   \n"), None);
        assert_eq!(outbound("pre-tool-use", r#"{"additionalContext":"  "}"#), None);
    }
}
